CREATE TABLE user_favorite_word (
  id BINARY(16) PRIMARY KEY,
  user_id BINARY(16) NOT NULL,
  lemma_key VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  lemma VARCHAR(128) NOT NULL,
  first_surface VARCHAR(128) NOT NULL,
  ipa_snapshot VARCHAR(256) NULL,
  pos_snapshot VARCHAR(24) NOT NULL,
  meaning_snapshot TEXT NOT NULL,
  dictionary_provider VARCHAR(64) NULL,
  dictionary_version VARCHAR(64) NULL,
  dictionary_dataset_id BINARY(16) NULL,
  dataset_version VARCHAR(64) NULL,
  entry_key VARCHAR(128) NULL,
  sense_key VARCHAR(128) NULL,
  lemma_method VARCHAR(64) NOT NULL,
  normalization_version VARCHAR(64) NOT NULL,
  created_at DATETIME(3) NOT NULL,
  UNIQUE KEY uq_favorite_lemma(user_id,lemma_key),
  KEY ix_favorite_user_created(user_id,created_at,id),
  CONSTRAINT fk_favorite_user FOREIGN KEY(user_id) REFERENCES app_user(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE favorite_word_context (
  id BINARY(16) PRIMARY KEY,
  favorite_word_id BINARY(16) NOT NULL,
  book_id BINARY(16) NULL,
  chapter_id BINARY(16) NULL,
  origin_key BINARY(16) NOT NULL,
  source_hash BINARY(32) NOT NULL,
  artifact_hash BINARY(32) NOT NULL,
  pipeline_version VARCHAR(64) NOT NULL,
  context_key BINARY(32) NOT NULL,
  spine_href VARCHAR(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  block_id VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  sentence_start INT NOT NULL,
  sentence_end INT NOT NULL,
  context_kind VARCHAR(16) NOT NULL,
  sentence_snapshot TEXT NOT NULL,
  surface_snapshot VARCHAR(128) NOT NULL,
  word_start INT NOT NULL,
  word_end INT NOT NULL,
  word_range_cfi TEXT NOT NULL,
  sentence_range_cfi TEXT NOT NULL,
  quote_prefix VARCHAR(128) NOT NULL,
  quote_suffix VARCHAR(128) NOT NULL,
  book_title_snapshot VARCHAR(512) NOT NULL,
  chapter_title_snapshot VARCHAR(512) NOT NULL,
  translation_id BINARY(16) NULL,
  translation_snapshot TEXT NULL,
  translation_provider VARCHAR(64) NULL,
  translated_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  UNIQUE KEY uq_favorite_context(favorite_word_id,context_key),
  KEY ix_context_origin(origin_key,favorite_word_id),
  KEY ix_context_book(book_id),
  KEY ix_context_created(favorite_word_id,created_at,id),
  CONSTRAINT fk_context_favorite FOREIGN KEY(favorite_word_id) REFERENCES user_favorite_word(id) ON DELETE CASCADE,
  CONSTRAINT fk_context_book FOREIGN KEY(book_id) REFERENCES book(id) ON DELETE SET NULL,
  CONSTRAINT fk_context_chapter FOREIGN KEY(chapter_id) REFERENCES book_chapter(id) ON DELETE SET NULL,
  CONSTRAINT ck_context_ranges CHECK(sentence_start >= 0 AND sentence_end > sentence_start AND word_start >= 0 AND word_end > word_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE mutation_receipt (
  user_id BINARY(16) NOT NULL,
  operation VARCHAR(32) NOT NULL,
  request_id BINARY(16) NOT NULL,
  request_hash BINARY(32) NOT NULL,
  status VARCHAR(16) NOT NULL,
  favorite_id BINARY(16) NULL,
  context_id BINARY(16) NULL,
  resource_state VARCHAR(16) NOT NULL,
  result_json JSON NULL,
  expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL,
  PRIMARY KEY(user_id,operation,request_id),
  KEY ix_mutation_expiry(expires_at),
  CONSTRAINT fk_mutation_user FOREIGN KEY(user_id) REFERENCES app_user(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
