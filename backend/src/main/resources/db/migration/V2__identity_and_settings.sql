CREATE TABLE app_user (
  id BINARY(16) NOT NULL,
  email VARCHAR(254) NULL,
  email_key VARCHAR(254) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  phone_e164 VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
  password_hash VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  email_verified BOOLEAN NOT NULL DEFAULT FALSE,
  phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(16) CHARACTER SET ascii NOT NULL DEFAULT 'ACTIVE',
  auth_version BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_user_email_key (email_key),
  UNIQUE KEY uk_user_phone (phone_e164),
  CONSTRAINT ck_user_identifier CHECK (email_key IS NOT NULL OR phone_e164 IS NOT NULL),
  CONSTRAINT ck_user_email_pair CHECK ((email IS NULL) = (email_key IS NULL)),
  CONSTRAINT ck_user_status CHECK (status IN ('ACTIVE','DISABLED')),
  CONSTRAINT ck_user_auth_version CHECK (auth_version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE user_settings (
  user_id BINARY(16) NOT NULL,
  font VARCHAR(32) NOT NULL DEFAULT 'Georgia',
  font_size SMALLINT NOT NULL DEFAULT 20,
  line_height DECIMAL(2,1) NOT NULL DEFAULT 1.8,
  content_width SMALLINT NOT NULL DEFAULT 660,
  theme VARCHAR(8) NOT NULL DEFAULT 'warm',
  pronunciation VARCHAR(5) NOT NULL DEFAULT 'en-GB',
  version BIGINT NOT NULL DEFAULT 1,
  last_request_id BINARY(16) NULL,
  last_request_hash BINARY(32) NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (user_id),
  CONSTRAINT fk_settings_user FOREIGN KEY (user_id) REFERENCES app_user(id),
  CONSTRAINT ck_settings_version CHECK (version >= 1),
  CONSTRAINT ck_settings_font CHECK (font IN ('Georgia','Palatino Linotype','Arial')),
  CONSTRAINT ck_settings_size CHECK (font_size IN (18,20,22,24)),
  CONSTRAINT ck_settings_line CHECK (line_height IN (1.6,1.8,2.0)),
  CONSTRAINT ck_settings_width CHECK (content_width IN (660,720)),
  CONSTRAINT ck_settings_theme CHECK (theme IN ('white','warm','dark')),
  CONSTRAINT ck_settings_voice CHECK (pronunciation IN ('en-GB','en-US')),
  CONSTRAINT ck_settings_request CHECK ((last_request_id IS NULL) = (last_request_hash IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
