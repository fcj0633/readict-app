CREATE TABLE reading_progress (
  book_id BINARY(16) NOT NULL,
  user_id BINARY(16) NOT NULL,
  artifact_id BINARY(16) NOT NULL,
  spine_href VARCHAR(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  cfi TEXT NOT NULL,
  block_id VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  block_offset INT NULL,
  quote_exact VARCHAR(256) NULL,
  quote_prefix VARCHAR(128) NULL,
  quote_suffix VARCHAR(128) NULL,
  progress_ratio DECIMAL(8,7) NOT NULL,
  version BIGINT NOT NULL,
  last_request_id BINARY(16) NOT NULL,
  last_request_hash BINARY(32) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (book_id),
  KEY ix_progress_user (user_id, updated_at, book_id),
  CONSTRAINT fk_progress_user FOREIGN KEY (user_id) REFERENCES app_user(id),
  CONSTRAINT fk_progress_book FOREIGN KEY (book_id) REFERENCES book(id),
  CONSTRAINT fk_progress_artifact FOREIGN KEY (artifact_id) REFERENCES book_artifact(id),
  CONSTRAINT ck_progress_ratio CHECK (progress_ratio >= 0 AND progress_ratio <= 1),
  CONSTRAINT ck_progress_offset CHECK (block_offset IS NULL OR block_offset >= 0),
  CONSTRAINT ck_progress_block CHECK ((block_id IS NULL) = (block_offset IS NULL)),
  CONSTRAINT ck_progress_quote CHECK ((quote_exact IS NULL) = (quote_prefix IS NULL)
    AND (quote_exact IS NULL) = (quote_suffix IS NULL)),
  CONSTRAINT ck_progress_cfi CHECK (CHAR_LENGTH(cfi) BETWEEN 1 AND 4096),
  CONSTRAINT ck_progress_version CHECK (version >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
